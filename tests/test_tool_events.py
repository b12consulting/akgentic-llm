class EventCapture:
    """Captures all domain events in emission order."""

    def __init__(self) -> None:
        self.events: list[object] = []

    def notify_event(self, event: object) -> None:
        """Append each received event for ordered assertion."""
        self.events.append(event)


def _make_manager_with_capture() -> tuple[ContextManager, EventCapture]:
    """Return a ContextManager wired to an EventCapture observer."""
    manager = ContextManager()
    capture = EventCapture()
    manager.subscribe(capture)
    return manager, capture


def _tool_call_msg(
    tool_name: str = "web_search_tool",
    tool_call_id: str = "call_abc123",
    args: str = '{"query": "test"}',
    run_id: uuid.UUID = RUN_ID,
) -> ModelResponse:
    return ModelResponse(
        parts=[ToolCallPart(tool_name=tool_name, tool_call_id=tool_call_id, args=args)],
        timestamp=datetime.now(),
        run_id=run_id,
    )


def _tool_return_msg(
    tool_name: str = "web_search_tool",
    tool_call_id: str = "call_abc123",
    content: str = "search results here",
    run_id: uuid.UUID = RUN_ID,
) -> ModelRequest:
    return ModelRequest(
        parts=[ToolReturnPart(tool_name=tool_name, tool_call_id=tool_call_id, content=content)],
        run_id=run_id,
    )


def _retry_with_id_msg(
    tool_name: str = "web_search_tool",
    tool_call_id: str = "call_abc123",
    content: str = "Tool raised error",
    run_id: uuid.UUID = RUN_ID,
) -> ModelRequest:
    return ModelRequest(
        parts=[RetryPromptPart(tool_name=tool_name, tool_call_id=tool_call_id, content=content)],
        run_id=run_id,
    )


def _retry_no_tool_name_msg(
    content: str = "Please retry in the correct format.",
    run_id: uuid.UUID = RUN_ID,
) -> ModelRequest:
    """Return a RetryPromptPart with tool_name=None (non-tool retry).

    Note: tool_call_id is always auto-generated by pydantic-ai (never None).
    The discriminator for tool vs. non-tool retry-prompts is tool_name, not tool_call_id.
    """
    return ModelRequest(parts=[RetryPromptPart(content=content)], run_id=run_id)


def _text_msg(
    content: str = "Hello world",
    run_id: uuid.UUID = RUN_ID,
) -> ModelResponse:
    return ModelResponse(
        parts=[TextPart(content=content)],
        timestamp=datetime.now(),
        run_id=run_id,
    )


